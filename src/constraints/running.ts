import type { GameState } from '../types';

/**
 * 게임이 실제로 굴러가는 중인지.
 * 플레이 중이고, 일시정지가 아니고, 사건 창도 떠 있지 않아야 시간이 흐릅니다.
 */
export function isRunning(state: GameState): boolean {
  return state.phase === 'playing' && !state.paused && state.activeEvent === null;
}
