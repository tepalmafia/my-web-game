/**
 * 레벨 L 에서 L+1 로 가는 데 필요한 경험치.
 * 앞은 금방 오르고 뒤로 갈수록 완만하게 무거워집니다.
 */
export function expToNextLevel(level: number): number {
  // 25레벨부터는 한 레벨마다 5%씩 더 무거워집니다.
  // 이게 없으면 마지막 열 레벨이 순식간에 지나가 후반이 밋밋해집니다.
  const lateWeight = 1 + Math.max(0, level - 25) * 0.05;
  return Math.round((30 * Math.pow(level, 2.05) + 20 * level) * lateWeight);
}

/** 도달할 수 있는 최고 레벨 */
export const MAX_LEVEL = 40;

/**
 * 나보다 한참 약한 몬스터를 잡을 때의 경험치 감소.
 * 이게 없으면 초원에서 끝까지 안전하게 레벨을 올릴 수 있어 사냥터를 옮길 이유가 사라집니다.
 */
export function expPenalty(playerLevel: number, monsterLevel: number): Ratio {
  const gap = playerLevel - monsterLevel;
  if (gap <= 5) return 1;
  return Math.max(0.08, 1 - (gap - 5) * 0.13);
}

