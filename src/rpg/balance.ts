/* ===========================================================================
 *  스킬 성장
 *  ---------------------------------------------------------------------------
 *  "행동하면 오른다"만으로는 부족합니다. 그러면 가장 쉬운 것을 무한히 반복하는 것이
 *  최적해가 되고, 자동사냥에서 걷어낸 문제가 채집에서 그대로 되살아납니다.
 *
 *  그래서 두 가지를 겁니다.
 *    ① 지금 스킬보다 한참 쉬운 일(난이도 < 스킬 - 20)에서는 아무것도 배우지 못한다
 *    ② 성장 확률은 스킬이 오를수록 급격히 떨어진다
 * ======================================================================== */

export const GAIN = {
  /** 스킬 0 에서 딱 맞는 난이도를 만났을 때의 성장 확률 */
  base: 0.62,
  /** 스킬이 오를수록 떨어지는 기울기 */
  falloff: 1.5,
  /**
   * 확률의 바닥.
   * ★ 이게 없으면 (1 - s/100)^n 이 0 으로 수렴해 100 에 수학적으로 도달할 수 없습니다.
   */
  floor: 0.035,
  /** 난이도가 (스킬 - 이 값) 미만이면 성장 없음 */
  easyCutoff: 20,
  /** 가장 잘 자라는 난이도 = 현재 스킬 + 이 값 */
  optimal: 5,
  /** 최적에서 멀어질수록 줄어드는 폭 */
  width: 18,
  /** 한 번 성장할 때 오르는 양 */
  step: 0.18,
} as const;

export const MAX_SKILL: SkillValue = 100;

/**
 *  스킬 총합 상한 — 딱딱한 상한입니다. 넘어서 안 오르고, 줄지도 않습니다.
 *
 *  ★ 능력치(STATS.totalMax)처럼 안 쓰는 것이 빠지는 방식을 쓰면 안 됩니다.
 *    검술을 놀려서 채광을 올릴 수 있게 되고, 그러면 길 선택이 시간만 들이면
 *    되돌려집니다 (전체설계 6.2).
 *
 *  ★ 세는 것은 예산을 먹는 스킬뿐입니다 (content/skills.ts 의 counts).
 *    셋 다 100 이면 300 이므로, 200 은 "둘을 채우고 하나는 버린다" 입니다.
 *
 *  ★ 200 은 오늘 콘텐츠에 대고 잰 값입니다. 오늘은 가장 어려운 몬스터가
 *    난이도 65(동굴 거미)뿐이라 검술이 85 에서 멈춥니다. C 에서 층이 생기면
 *    난이도 천장이 올라가므로 이 값은 그때 다시 잽니다.
 */
export const SKILL_TOTAL_MAX: SkillValue = 200;

/**
 * 이 스킬로 이 난이도의 일을 했을 때, 한 번 시도에 스킬이 오를 확률.
 * 성공했든 실패했든 굴립니다 — 실패에서도 배웁니다.
 */
export function gainChance(skill: SkillValue, difficulty: Difficulty): Ratio {
  if (skill >= MAX_SKILL) return 0;
  if (difficulty < skill - GAIN.easyCutoff) return 0;

  const decay = Math.max(GAIN.floor, Math.pow(1 - skill / MAX_SKILL, GAIN.falloff));
  const bell = Math.exp(-((difficulty - skill - GAIN.optimal) ** 2) / (2 * GAIN.width ** 2));
  return GAIN.base * decay * bell;
}

