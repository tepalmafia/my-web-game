/**
 * ===========================================================================
 *  AGI 경주 게임 — 데이터 구조 확정본
 * ===========================================================================
 *
 *  이 파일은 게임에 등장하는 "모든 정보의 설계도"입니다.
 *  집으로 치면 도면에 해당하고, 앞으로 만들 코드는 전부 이 도면을 따릅니다.
 *
 *  ─ 이 파일에 들어가는 것
 *      · 어떤 정보가 존재하는가 (예: 플레이어는 자금과 GPU를 가진다)
 *      · 각 정보가 어떤 형태인가 (숫자인가, 글자인가, 목록인가)
 *
 *  ─ 이 파일에 들어가지 않는 것
 *      · 실제 숫자 (GPU 가격 5만 달러, 훈련 속도 등) → balance.ts 에 따로 둡니다
 *      · 계산 방법 (돈을 어떻게 깎는지)                → 게임 로직 파일에 둡니다
 *      · 화면 모양 (버튼 색, 배치)                     → 화면 파일에 둡니다
 *
 *    즉 밸런스를 아무리 고쳐도 이 파일은 그대로입니다.
 *    이 파일이 바뀐다는 건 "게임에 없던 개념이 새로 생겼다"는 뜻이므로,
 *    그때는 반드시 상의한 뒤에 바꿉니다.
 *
 *  ※ `?` 가 붙은 항목은 "없을 수도 있는 값"이라는 뜻입니다.
 *  ※ `|` 는 "이 중 하나"라는 뜻입니다. (예: 'win' | 'lose' → 둘 중 하나)
 */

/* ===========================================================================
 *  0. 단위 이름표
 *  ---------------------------------------------------------------------------
 *  전부 그냥 숫자(number)지만, 이름을 붙여두면 코드를 읽을 때
 *  "이 숫자가 돈인지 시간인지"가 바로 보입니다. 실수를 크게 줄여줍니다.
 * ======================================================================== */

/** 돈 (단위: 달러). 예) 1_500_000 = 150만 달러 */
export type Money = number;

/** 전력 (단위: MW, 메가와트). 대형 데이터센터 한 동이 수십~수백 MW를 씁니다 */
export type Megawatts = number;

/** 시간 (단위: 초) */
export type Seconds = number;

/** 비율 (0 = 0%, 1 = 100%). 진행도·안전도처럼 0~1 사이 값에 씁니다 */
export type Ratio = number;

/** 1초당 오르는 비율. 예) 0.001 이면 1초에 0.1%씩 진행 */
export type RatioPerSecond = number;

/** 배수 (1 = 변화 없음, 2 = 두 배, 0.5 = 절반) */
export type Multiplier = number;

/** 경쟁사를 구분하는 고유 이름표. 예) 'rival-helion' */
export type RivalId = string;

/** 사건을 구분하는 고유 이름표. 예) 'event-gpu-shortage' */
export type EventId = string;

/* ===========================================================================
 *  1. 플레이어 — 내 연구소가 가진 정보
 *  ---------------------------------------------------------------------------
 *  여기 담기는 값은 전부 "원본 사실"입니다.
 *  계산해서 알 수 있는 값(전력 소비량, 초당 연구 속도 등)은 절대 넣지 않습니다.
 *  → 그런 값은 아래 6번 DerivedStats 에서 매번 새로 계산합니다.
 *    (저장해두면 실제 값과 어긋나는 버그가 반드시 생깁니다)
 * ======================================================================== */

export interface PlayerState {
  /** 내 연구소 이름. 화면 상단과 엔딩 문구에 쓰입니다 */
  labName: string;

  // ── 자원 4종 ──────────────────────────────────────────────

  /** 보유 자금. 0 밑으로 내려가면 파산 패배 */
  money: Money;

  /** 보유 GPU 수(장). 데이터센터 수용 한도를 넘겨서는 살 수 없습니다 */
  gpus: number;

  /**
   * 전력 회사와 계약해둔 용량(MW).
   * 실제로 다 쓰든 안 쓰든 계약한 만큼 매초 요금이 나갑니다.
   * 이 값이 GPU가 필요로 하는 전력보다 적으면 일부 GPU가 놀게 됩니다.
   */
  powerContracted: Megawatts;

  /** AGI 진행도 (0 = 0%, 1 = 100% → 승리) */
  researchProgress: Ratio;

  // ── 시설과 인력 ───────────────────────────────────────────

  /** 지은 데이터센터 수(동). GPU를 몇 장까지 둘 수 있는지를 결정합니다 */
  datacenters: number;

  /** 고용한 연구원 수(명). 같은 GPU로도 훈련이 더 빨라집니다. 매초 인건비가 나갑니다 */
  researchers: number;

  // ── 자금 조달 ─────────────────────────────────────────────

  /**
   * 지금까지 투자를 받은 횟수.
   * 라운드가 올라갈수록 한 번에 들어오는 금액이 커지는 대신 지분을 더 많이 내줍니다.
   */
  fundingRound: number;

  /**
   * 내가 아직 들고 있는 지분 (1 = 100%, 0.4 = 40%).
   * 투자를 받을 때마다 줄어들고, 바닥나면 더 이상 투자를 받을 수 없습니다.
   * → "돈이 필요하면 계속 눌러라" 식의 무한 반복을 막는 장치입니다.
   */
  equityRetained: Ratio;

  // ── 위험 관리 ─────────────────────────────────────────────

  /**
   * 안전 검증 수준 (1 = 원칙대로 전부 검증, 0 = 전부 건너뛰고 질주).
   * 낮출수록 훈련 속도가 올라가지만 사고 확률이 함께 올라갑니다.
   * 사고가 터지면 즉시 패배(catastrophe)입니다.
   */
  safety: Ratio;
}

/* ===========================================================================
 *  2. 적 — 경쟁 연구소
 *  ---------------------------------------------------------------------------
 *  경쟁사는 플레이어처럼 GPU를 사고 전기를 계약하지 않습니다.
 *  20~30분짜리 게임에서 그렇게까지 만들면 만들 것만 3배로 늘고
 *  플레이어 눈에는 어차피 "막대가 얼마나 찼는지"만 보이기 때문입니다.
 *  대신 성향에 따라 속도가 달라지는 방식으로 단순하게 굴립니다.
 * ======================================================================== */

/** 경쟁사의 성향. 진행 속도가 시간에 따라 어떤 모양으로 변하는지를 결정합니다 */
export type RivalPersonality =
  /** 자금력형: 돈으로 GPU를 쓸어담아 처음부터 끝까지 꾸준히 빠름 */
  | 'capital'
  /** 속도형: 안전을 무시하고 질주. 가장 빠르지만 스스로 사고를 낼 수 있음 */
  | 'speed'
  /** 효율형: 초반엔 느리지만 후반으로 갈수록 가속 */
  | 'efficiency';

/** 경쟁사의 현재 상태. 상황판에 표시할 문구와 색을 정하는 데 씁니다 */
export type RivalStatus =
  /** 평소 속도로 추격 중 */
  | 'racing'
  /** 가속 구간 (막판 스퍼트, 대형 투자 유치 등) */
  | 'sprinting'
  /** 공급난·규제·정전 등으로 정체 중 */
  | 'stalled'
  /** 사고로 자멸해 경주에서 탈락 (더 이상 진행하지 않음) */
  | 'collapsed'
  /** AGI 달성 → 플레이어 패배 */
  | 'achieved';

export interface Rival {
  /** 구분용 고유 이름표 */
  id: RivalId;

  /** 화면에 표시할 이름. 예) '헬리온 리서치' */
  name: string;

  /** 성향 */
  personality: RivalPersonality;

  /**
   * 진짜 진행도 (0~1). 승패 판정은 이 값으로만 합니다.
   * 1에 도달하면 이 경쟁사가 이기고 플레이어는 패배합니다.
   */
  researchProgress: Ratio;

  /**
   * 플레이어 상황판에 보여줄 추정 진행도.
   * 경쟁사 내부 사정을 정확히 알 수는 없다는 설정이라 진짜 값과 조금 다를 수 있습니다.
   * (추측 요소를 안 쓰기로 하면 researchProgress 와 같은 값을 넣으면 됩니다)
   */
  reportedProgress: Ratio;

  /** 성향에서 나오는 기본 진행 속도 (1초에 오르는 진행도) */
  baseSpeed: RatioPerSecond;

  /**
   * 지금 붙어 있는 속도 배수 (1 = 기본, 1.5 = 50% 빨라짐, 0 = 완전 정지).
   * 사건이나 후반 스퍼트로 실시간으로 바뀝니다.
   */
  momentum: Multiplier;

  /** 현재 상태 */
  status: RivalStatus;
}

/* ===========================================================================
 *  3. 점진적 해금 — 지금 화면에 무엇이 보이는가
 *  ---------------------------------------------------------------------------
 *  "처음엔 버튼 2개만 보이고 진행할수록 늘어난다"는 규칙을 담는 곳입니다.
 * ======================================================================== */

/** 화면에 나타났다 사라졌다 하는 영역들의 이름표 */
export type PanelId =
  /** 투자 유치 (게임 시작부터 열려 있음) */
  | 'funding'
  /** GPU 구매 (게임 시작부터 열려 있음) */
  | 'gpu'
  /** 전력 계약 (전력이 모자라 훈련이 멈추는 순간 열림) */
  | 'power'
  /** 데이터센터 건설 (GPU 수용 한도가 꽉 차면 열림) */
  | 'datacenter'
  /** 연구원 채용 (자금이 일정 수준을 넘으면 열림) */
  | 'researchers'
  /** 경쟁사 상황판 (진행도가 일정 수준을 넘으면 열림) */
  | 'rivals'
  /** 안전 수준 조절 (후반에 열리는 위험한 선택) */
  | 'safety';

/**
 * 각 영역이 열렸는지 여부.
 * 예) { funding: true, gpu: true, power: false, ... }
 * 한 번 열린 영역은 다시 닫히지 않습니다.
 */
export type UnlockState = Record<PanelId, boolean>;

/* ===========================================================================
 *  4. 시장 상황 — 사건 때문에 흔들리는 바깥 세상
 * ======================================================================== */

export interface MarketState {
  /** GPU 가격 배수 (1 = 정상가, 2.5 = 공급난으로 2.5배) */
  gpuPrice: Multiplier;

  /** 전기 요금 배수 (1 = 정상가) */
  powerPrice: Multiplier;

  /**
   * 위 배수들이 정상(1)으로 돌아오기까지 남은 시간(초).
   * 0이면 이미 정상 상태입니다.
   */
  distortionRemaining: Seconds;
}

/* ===========================================================================
 *  5. 사건과 로그
 *  ---------------------------------------------------------------------------
 *  사건은 "글로 적어두면 게임에 반영되는" 방식으로 만듭니다.
 *  덕분에 새 사건을 추가할 때 코드를 짤 필요 없이
 *  events.ts 에 블록 하나를 복사해 문구와 숫자만 고치면 됩니다.
 * ======================================================================== */

/** 사건의 종류. 같은 종류가 연달아 나오지 않게 조절하는 데 씁니다 */
export type EventKind =
  /** GPU 공급망 (품귀, 신제품 출시, 밀수 제안) */
  | 'supply'
  /** 전력 (정전, 요금 인상, 발전소 계약) */
  | 'power'
  /** 규제 (감사, 수출 통제, 청문회) */
  | 'regulation'
  /** 인재 (스카웃 제안, 핵심 연구원 이탈) */
  | 'talent'
  /** 안전 (내부 경고, 사고 징후) */
  | 'safety'
  /** 기회 (대형 투자 제안, 협업 제안) */
  | 'opportunity';

/**
 * 선택지를 고르려면 최소한 이만큼은 갖고 있어야 한다는 조건.
 * 조건에 못 미치면 그 버튼은 눌리지 않게 표시됩니다.
 * 적지 않은 항목은 조건이 없다는 뜻입니다.
 */
export interface Requirement {
  /** 최소 보유 자금 */
  money?: Money;
  /** 최소 보유 GPU 수 */
  gpus?: number;
  /** 최소 연구원 수 */
  researchers?: number;
  /** 최소 데이터센터 수 */
  datacenters?: number;
}

/**
 * 플레이어 값이 얼마나 변하는지 (증감량).
 * 예) { money: -2_000_000, gpus: 500 } → 200만 달러 쓰고 GPU 500장 얻음
 * 적지 않은 항목은 "변화 없음"입니다.
 */
export interface PlayerDelta {
  money?: Money;
  gpus?: number;
  powerContracted?: Megawatts;
  researchProgress?: Ratio;
  datacenters?: number;
  researchers?: number;
  equityRetained?: Ratio;
  safety?: Ratio;
}

/** 시장이 어떻게 흔들리는지 */
export interface MarketDelta {
  /** GPU 가격 배수를 이 값으로 바꿈 */
  gpuPrice?: Multiplier;
  /** 전기 요금 배수를 이 값으로 바꿈 */
  powerPrice?: Multiplier;
  /** 이 상태가 몇 초 동안 지속되는지 */
  durationSeconds?: Seconds;
}

/** 경쟁사가 어떤 영향을 받는지 */
export interface RivalDelta {
  /** 누구에게 적용할지: 전체 / 1등 / 무작위 한 곳 */
  target: 'all' | 'leader' | 'random';
  /** 속도 배수를 이 값으로 바꿈 */
  momentum?: Multiplier;
  /** 진행도를 이만큼 더하거나 뺌 */
  researchProgress?: Ratio;
  /** 상태를 이 값으로 바꿈 */
  status?: RivalStatus;
}

/** 사건 창에 뜨는 버튼 하나 */
export interface EventChoice {
  /** 버튼 글자. 예) '웃돈을 주고 물량을 확보한다' */
  label: string;

  /** 버튼 아래 작은 글씨. 결과를 살짝 귀띔해줍니다 */
  hint?: string;

  /** 이 버튼을 누를 수 있는 최소 조건. 없으면 항상 누를 수 있습니다 */
  requires?: Requirement;

  /** 이 버튼을 눌렀을 때 내 연구소에 생기는 변화 */
  player?: PlayerDelta;

  /** 이 버튼을 눌렀을 때 시장에 생기는 변화 */
  market?: MarketDelta;

  /** 이 버튼을 눌렀을 때 경쟁사에 생기는 변화 */
  rivals?: RivalDelta;

  /** 선택 직후 로그창에 남길 문장 */
  logText: string;

  /** 그 문장의 색깔 */
  logTone: LogTone;
}

/** 화면에 떠서 결정을 요구하는 사건 하나 */
export interface GameEvent {
  /** 구분용 고유 이름표 */
  id: EventId;

  /** 종류 */
  kind: EventKind;

  /** 제목. 예) 'TSMC 물량 배정 실패' */
  title: string;

  /** 본문 설명 (두세 문장) */
  description: string;

  /**
   * 이 사건이 등장할 수 있는 가장 이른 게임 시각(초).
   * 시작하자마자 어려운 사건이 튀어나오는 걸 막습니다.
   */
  earliestAt: Seconds;

  /** true 면 한 판에 한 번만 등장합니다 */
  once: boolean;

  /**
   * 선택지 목록.
   * 1개만 있으면 '확인'만 누르는 통보성 사건이 됩니다.
   */
  choices: EventChoice[];
}

/** 로그 한 줄의 색깔 */
export type LogTone =
  /** 평범한 알림 (회색) */
  | 'info'
  /** 좋은 소식 (초록) */
  | 'good'
  /** 주의 (노랑) */
  | 'warn'
  /** 나쁜 소식 (빨강) */
  | 'bad';

/** 오른쪽 로그창에 쌓이는 줄 하나 */
export interface LogEntry {
  /** 화면이 목록을 구분하는 데 쓰는 번호. 1부터 하나씩 올라갑니다 */
  id: number;

  /** 이 일이 벌어진 게임 내 시각(초) */
  at: Seconds;

  /** 표시할 문장 */
  text: string;

  /** 색깔 */
  tone: LogTone;
}

/* ===========================================================================
 *  6. 게임 상태 — 위의 모든 것을 담는 하나의 큰 상자
 *  ---------------------------------------------------------------------------
 *  게임에 관한 정보는 100% 이 안에 들어 있습니다.
 *  이 상자 하나만 통째로 복사하면 그 순간의 게임이 완벽히 재현됩니다.
 *  (나중에 저장 기능이나 자동 테스트를 붙일 때 이 성질이 큰 도움이 됩니다)
 * ======================================================================== */

/** 게임이 지금 어느 국면인지 */
export type GamePhase =
  /** 시작 화면 (연구소 이름 입력) */
  | 'title'
  /** 플레이 중 */
  | 'playing'
  /** 끝남 (승리 또는 패배 화면) */
  | 'ended';

/** 게임이 끝난 이유 */
export type GameOutcome =
  /** 승리 — 내가 먼저 AGI에 도달 */
  | 'agiAchieved'
  /** 패배 — 경쟁사가 먼저 도달 */
  | 'rivalWon'
  /** 패배 — 자금이 바닥나 운영 불가 */
  | 'bankrupt'
  /** 패배 — 안전을 무시하다 사고 발생 */
  | 'catastrophe';

export interface GameState {
  // ── 진행 국면 ─────────────────────────────────────────────

  /** 지금 어느 화면인지 */
  phase: GamePhase;

  /** 끝난 이유. 아직 진행 중이면 null */
  outcome: GameOutcome | null;

  /** 나를 이긴 경쟁사. outcome 이 'rivalWon' 일 때만 값이 들어갑니다 */
  outcomeRivalId: RivalId | null;

  /** 플레이어가 일시정지 버튼을 눌렀는지 */
  paused: boolean;

  /**
   * 사건 창이 떠 있으면 그 사건, 없으면 null.
   * 사건 창이 떠 있는 동안에는 시간이 흐르지 않습니다.
   */
  activeEvent: GameEvent | null;

  // ── 시간 ──────────────────────────────────────────────────

  /** 시작 후 흐른 게임 내 시간(초) */
  elapsed: Seconds;

  /** 계산을 몇 번 돌렸는지. 0.1초마다 1씩 증가합니다 (디버깅과 재현용) */
  tick: number;

  /** 게임 진행 속도 (1 = 기본, 2 = 2배속). 답답할 때와 테스트할 때 씁니다 */
  speed: Multiplier;

  // ── 등장인물 ──────────────────────────────────────────────

  /** 내 연구소 */
  player: PlayerState;

  /** 경쟁 연구소 목록 (3곳) */
  rivals: Rival[];

  // ── 세상 ──────────────────────────────────────────────────

  /** 지금 화면에 열려 있는 영역들 */
  unlocks: UnlockState;

  /** GPU 값과 전기 요금이 지금 어떤 상태인지 */
  market: MarketState;

  /** 다음 사건이 터지기까지 남은 시간(초) */
  nextEventIn: Seconds;

  /** 이미 나왔던 사건들의 이름표. once 사건이 두 번 나오지 않게 막습니다 */
  seenEventIds: EventId[];

  // ── 기록 ──────────────────────────────────────────────────

  /** 사건 로그. 최신 항목이 배열 맨 앞에 옵니다 */
  log: LogEntry[];

  /** 다음 로그에 붙일 번호 */
  nextLogId: number;

  /**
   * 난수 씨앗.
   * 같은 씨앗으로 시작하면 사건 순서까지 똑같은 판이 그대로 재현됩니다.
   * "이 밸런스가 정말 재밌나"를 자동으로 여러 번 돌려볼 때 꼭 필요합니다.
   */
  rngSeed: number;
}

/* ===========================================================================
 *  7. 계산해서 얻는 값 — 저장하지 않는 값들
 *  ---------------------------------------------------------------------------
 *  아래 값들은 GameState 안에 절대 넣지 않습니다.
 *  넣는 순간 "GPU를 팔았는데 전력 소비량이 그대로인" 종류의 버그가 생깁니다.
 *  대신 화면을 그릴 때마다 GameState 를 보고 즉석에서 계산합니다.
 * ======================================================================== */

export interface DerivedStats {
  /** 지금 시간이 흐르고 있는지 (플레이 중 + 일시정지 아님 + 사건 창 없음) */
  running: boolean;

  // ── 설비 ──────────────────────────────────────────────────

  /** GPU를 최대 몇 장까지 둘 수 있는지 (데이터센터 수 × 한 동당 수용량) */
  gpuCapacity: number;

  /** 보유 GPU를 전부 돌리려면 필요한 전력(MW) */
  powerDemand: Megawatts;

  /**
   * 계약 전력으로 실제 돌아가고 있는 GPU 수.
   * 전력이 모자라면 보유량보다 적어지고, 그만큼 훈련이 느려집니다.
   */
  activeGpus: number;

  /** 전력 여유율 (1 = 넉넉함, 0 = 완전히 모자람) */
  powerHeadroom: Ratio;

  // ── 속도 ──────────────────────────────────────────────────

  /** 1초에 오르는 AGI 진행도 */
  researchRate: RatioPerSecond;

  /** 지금 속도라면 AGI까지 남은 시간(초). 진행이 멈춰 있으면 null */
  etaToAgi: Seconds | null;

  // ── 돈 ────────────────────────────────────────────────────

  /** 1초에 나가는 돈 (전기 요금 + 연구원 인건비 + 데이터센터 유지비) */
  burnPerSecond: Money;

  /** 1초에 들어오는 돈 (지금까지 만든 모델을 서비스해서 버는 매출) */
  revenuePerSecond: Money;

  /** 수입 − 지출. 음수면 통장이 마르고 있다는 뜻 */
  netPerSecond: Money;

  /** 지금 자금으로 몇 초나 더 버틸 수 있는지. 흑자면 null */
  runwaySeconds: Seconds | null;

  // ── 경쟁 ──────────────────────────────────────────────────

  /** 가장 앞서 있는 경쟁사. 아직 상황판이 안 열렸어도 내부적으로는 계산합니다 */
  leadingRival: Rival | null;

  /** 1등 경쟁사와 나의 진행도 차이 (양수면 내가 앞섬) */
  leadMargin: Ratio;
}

/* ===========================================================================
 *  8. 액션 — 버튼이 게임에 보내는 신호
 *  ---------------------------------------------------------------------------
 *  화면(버튼)은 게임 상태를 직접 고치지 않습니다.
 *  대신 "투자를 유치하겠다" 같은 신호만 보내고, 실제 계산은 로직이 담당합니다.
 *  이렇게 나눠두면 버튼을 누르지 않고도 자동으로 게임을 돌려볼 수 있어서
 *  밸런스를 기계로 검사할 수 있게 됩니다.
 * ======================================================================== */

export type GameAction =
  /** 게임 시작 (시작 화면에서 연구소 이름을 정하고 진입) */
  | { type: 'startGame'; labName: string; rngSeed: number }

  /** 시간이 흘렀음 (0.1초마다 자동으로 발생) */
  | { type: 'tick'; deltaSeconds: Seconds }

  /** 투자 유치 버튼 */
  | { type: 'raiseFunding' }

  /** GPU 구매 버튼 (한 번에 몇 장 살지) */
  | { type: 'buyGpu'; count: number }

  /** 전력 계약 버튼 (몇 MW를 추가로 계약할지) */
  | { type: 'contractPower'; megawatts: Megawatts }

  /** 데이터센터 건설 버튼 */
  | { type: 'buildDatacenter' }

  /** 연구원 채용 버튼 (한 번에 몇 명 뽑을지) */
  | { type: 'hireResearcher'; count: number }

  /** 안전 수준 조절 (0~1 사이 값으로 설정) */
  | { type: 'setSafety'; value: Ratio }

  // ── 경쟁사 대응 ────────────────────────────────────────────
  //  경쟁사를 '달리는 막대'가 아니라 손댈 수 있는 상대로 만드는 행동들입니다.
  //  (이 셋은 나중에 추가됐습니다 — 그전까지 경쟁사는 개입할 방법이 전혀 없어서
  //   사실상 제한시간을 알려주는 시계일 뿐이었습니다)

  /** 돈을 주고 경쟁사 한 곳의 '진짜' 진행도를 알아냅니다 */
  | { type: 'buyIntel'; rivalId: RivalId }

  /** 경쟁사 한 곳의 핵심 인력을 데려옵니다 (상대는 느려지고 내 연구원은 늘어납니다) */
  | { type: 'poachRival'; rivalId: RivalId }

  /** GPU 물량을 미리 사재기해 경쟁사 전체를 늦춥니다 (대신 내 GPU 값도 오릅니다) */
  | { type: 'lockSupply' }

  /** 사건 창에서 선택지를 고름 (몇 번째 버튼인지) */
  | { type: 'resolveEvent'; choiceIndex: number }

  /** 일시정지 켜기/끄기 */
  | { type: 'setPaused'; paused: boolean }

  /** 게임 속도 변경 */
  | { type: 'setSpeed'; speed: Multiplier }

  /** 처음부터 다시 하기 */
  | { type: 'restart' };
